class CombatListenerTest {

    private FirstPlugin plugin;

    @BeforeEach
    void setUp() {
        MockBukkit.mock();
        plugin = MockBukkit.load(FirstPlugin.class);
    }

    @AfterEach
    void tearDown() {
        MockBukkit.unmock();
    }

    @Test
    void playerDamageTurnsChatAndTabNamesRedAndRestoresThemAfterCooldown() {
        Player attacker = MockBukkit.getMock().addPlayer();
        Player victim = MockBukkit.getMock().addPlayer();
        Component originalChatName = Component.text("Chat name", NamedTextColor.BLUE);
        Component originalTabName = Component.text("Tab name", NamedTextColor.GREEN);
        attacker.displayName(originalChatName);
        attacker.playerListName(originalTabName);

        damage(attacker, victim);

        assertEquals(NamedTextColor.RED, attacker.displayName().color());
        assertEquals(NamedTextColor.RED, attacker.playerListName().color());
        assertEquals(NamedTextColor.RED, victim.displayName().color());
        assertEquals(NamedTextColor.RED, victim.playerListName().color());

        MockBukkit.getMock().getScheduler().performTicks(299);
        assertEquals(NamedTextColor.RED, attacker.displayName().color());

        MockBukkit.getMock().getScheduler().performOneTick();
        assertEquals(originalChatName, attacker.displayName());
        assertEquals(originalTabName, attacker.playerListName());
        assertNull(victim.displayName().color());
    }

    @Test
    void anotherHitRefreshesTheCombatCooldown() throws InterruptedException {
        Player attacker = MockBukkit.getMock().addPlayer();
        Player victim = MockBukkit.getMock().addPlayer();
        attacker.displayName(Component.text("Attacker", NamedTextColor.BLUE));

        damage(attacker, victim);
        MockBukkit.getMock().getScheduler().performTicks(100);
        Thread.sleep(2);
        damage(attacker, victim);

        MockBukkit.getMock().getScheduler().performTicks(100);
        assertEquals(NamedTextColor.RED, attacker.displayName().color());

        MockBukkit.getMock().getScheduler().performTicks(199);
        assertEquals(NamedTextColor.RED, attacker.displayName().color());

        MockBukkit.getMock().getScheduler().performOneTick();
        assertEquals(NamedTextColor.BLUE, attacker.displayName().color());
    }

    @Test
    void projectileDamageTagsBothPlayersAndBlocksPunchBow() {
        Player attacker = MockBukkit.getMock().addPlayer();
        Player victim = MockBukkit.getMock().addPlayer();
        ItemStack bow = new ItemStack(Material.BOW);
        bow.addUnsafeEnchantment(Enchantment.PUNCH, 2);
        attacker.getInventory().setItemInMainHand(bow);
        World world = attacker.getWorld();
        Arrow arrow = world.spawnArrow(new Location(world, 0, 64, 0), attacker.getLocation().getDirection(), 1, 0);
        arrow.setShooter(attacker);

        plugin.getServer().getPluginManager().callEvent(new EntityDamageByEntityEvent(
                arrow, victim, EntityDamageEvent.DamageCause.PROJECTILE, 1));

        assertEquals(NamedTextColor.RED, attacker.displayName().color());
        assertEquals(NamedTextColor.RED, victim.displayName().color());

        EntityShootBowEvent bowShoot = new EntityShootBowEvent(attacker, bow, arrow, 1);
        plugin.getServer().getPluginManager().callEvent(bowShoot);
        assertTrue(bowShoot.isCancelled());
    }

    @Test
    void nonPlayerDamageDoesNotStartCombat() {
        Player player = MockBukkit.getMock().addPlayer();
        World world = player.getWorld();
        var zombie = world.spawnEntity(new Location(world, 0, 64, 0), EntityType.ZOMBIE);

        plugin.getServer().getPluginManager().callEvent(new EntityDamageByEntityEvent(
                zombie, player, EntityDamageEvent.DamageCause.ENTITY_ATTACK, 1));

        assertNull(player.displayName().color());
        assertFalse(interactionIsDenied(interact(player, Material.ENDER_PEARL, Action.RIGHT_CLICK_AIR)));
    }

    @Test
    void enchantedGoldenApplesAreBlockedOnlyOnRightClickWhilePvpIsEnabled() {
        Player attacker = MockBukkit.getMock().addPlayer();
        Player victim = MockBukkit.getMock().addPlayer();
        damage(attacker, victim);

        assertFalse(interactionIsDenied(interact(victim, Material.GOLDEN_APPLE, Action.RIGHT_CLICK_AIR)));
        assertTrue(interactionIsDenied(interact(victim, Material.ENCHANTED_GOLDEN_APPLE, Action.RIGHT_CLICK_BLOCK)));
        assertFalse(interactionIsDenied(interact(victim, Material.ENCHANTED_GOLDEN_APPLE, Action.LEFT_CLICK_AIR)));
    }

    @Test
    void pearlsAndRiptideAreBlockedDuringCombat() {
        Player attacker = MockBukkit.getMock().addPlayer();
        Player victim = MockBukkit.getMock().addPlayer();
        damage(attacker, victim);

        assertTrue(interactionIsDenied(interact(victim, Material.ENDER_PEARL, Action.RIGHT_CLICK_AIR)));

        ItemStack riptideTrident = new ItemStack(Material.TRIDENT);
        riptideTrident.addUnsafeEnchantment(Enchantment.RIPTIDE, 1);
        assertTrue(interactionIsDenied(interact(victim, riptideTrident, Action.RIGHT_CLICK_AIR)));
        assertFalse(interactionIsDenied(interact(victim, Material.TRIDENT, Action.RIGHT_CLICK_AIR)));
    }

    @Test
    void restrictedItemsAreAllowedOutsideCombat() {
        Player player = MockBukkit.getMock().addPlayer();

        assertFalse(interactionIsDenied(interact(player, Material.GOLDEN_APPLE, Action.RIGHT_CLICK_AIR)));
        assertFalse(interactionIsDenied(interact(player, Material.ENDER_PEARL, Action.RIGHT_CLICK_AIR)));
        assertFalse(interactionIsDenied(interact(player, (ItemStack) null, Action.RIGHT_CLICK_AIR)));
    }

    @Test
    void elytraFlightIsBlockedOnlyWhenGlidingDuringCombat() {
        Player attacker = MockBukkit.getMock().addPlayer();
        Player victim = MockBukkit.getMock().addPlayer();
        damage(attacker, victim);
        victim.setGliding(true);

        EntityToggleGlideEvent combatGlide = new EntityToggleGlideEvent(victim, true);
        plugin.getServer().getPluginManager().callEvent(combatGlide);
        assertTrue(combatGlide.isCancelled());

        Player untaggedPlayer = MockBukkit.getMock().addPlayer();
        EntityToggleGlideEvent untaggedGlide = new EntityToggleGlideEvent(untaggedPlayer, true);
        plugin.getServer().getPluginManager().callEvent(untaggedGlide);
        assertFalse(untaggedGlide.isCancelled());
    }

    @Test
    void restrictedPotionEffectsAreBlockedAndOtherEffectsAreAllowed() {
        Player player = MockBukkit.getMock().addPlayer();

        for (PotionEffectType type : new PotionEffectType[]{
                PotionEffectType.POISON,
                PotionEffectType.WEAKNESS,
                PotionEffectType.SLOWNESS,
                PotionEffectType.SLOW_FALLING
        }) {
            assertTrue(potionEffect(player, type).isCancelled(), type.key().toString());
        }
        assertFalse(potionEffect(player, PotionEffectType.SPEED).isCancelled());
    }

    @Test
    void quittingDuringCombatRestoresSavedNames() {
        Player attacker = MockBukkit.getMock().addPlayer();
        Player victim = MockBukkit.getMock().addPlayer();
        Component originalName = Component.text("Player", NamedTextColor.BLUE);
        attacker.displayName(originalName);

        damage(attacker, victim);
        plugin.getServer().getPluginManager().callEvent(new PlayerQuitEvent(attacker, Component.empty()));

        assertEquals(originalName, attacker.displayName());
        assertFalse(interactionIsDenied(interact(attacker, Material.ENDER_PEARL, Action.RIGHT_CLICK_AIR)));
    }

    private void damage(Player attacker, Player victim) {
        plugin.getServer().getPluginManager().callEvent(new EntityDamageByEntityEvent(
                attacker, victim, EntityDamageEvent.DamageCause.ENTITY_ATTACK, 1));
    }

    private PlayerInteractEvent interact(Player player, Material material, Action action) {
        return interact(player, new ItemStack(material), action);
    }

    private PlayerInteractEvent interact(Player player, ItemStack item, Action action) {
        PlayerInteractEvent event = new PlayerInteractEvent(player, action, item, null, BlockFace.SELF);
        event.setUseInteractedBlock(Event.Result.DEFAULT);
        event.setUseItemInHand(Event.Result.DEFAULT);
        plugin.getServer().getPluginManager().callEvent(event);
        return event;
    }

    private boolean interactionIsDenied(PlayerInteractEvent event) {
        return event.useItemInHand() == Event.Result.DENY;
    }

    private EntityPotionEffectEvent potionEffect(Player player, PotionEffectType type) {
        EntityPotionEffectEvent event = new EntityPotionEffectEvent(
                player,
                null,
                new PotionEffect(type, 100, 0),
                null,
                EntityPotionEffectEvent.Cause.POTION_DRINK,
                EntityPotionEffectEvent.Action.ADDED,
                false);
        plugin.getServer().getPluginManager().callEvent(event);
        return event;
    }
}
